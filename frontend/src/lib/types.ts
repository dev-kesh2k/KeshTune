export type ArtistRef = { id: string; name: string };
export type Track = {
  id: string;
  title: string;
  duration_ms: number;
  explicit: boolean;
  source: 'file' | 'youtube';
  youtube_id?: string;
  playable: boolean;
  unavailable_reason?: string;
  downloadable: boolean;
  popularity: number;
  track_number: number | null;
  has_lyrics: boolean;
  cover_url: string | null;
  album: { id: string; title: string } | null;
  artists: ArtistRef[];
  liked: boolean;
};
export type AlbumCard = { id: string; title: string; type: string; release_date: string | null; cover_url: string | null; artists: ArtistRef[] };
export type PlaylistCard = {
  id: string;
  name: string;
  description: string | null;
  cover_url: string | null;
  visibility: 'private' | 'public' | 'link';
  is_collaborative: boolean;
  owner_id: string;
  owner_name: string;
  track_count: number;
  mosaic: string[];
  folder_id?: string | null;
};
export type ArtistCard = { id: string; name: string; image_url: string | null; verified?: boolean };
export type Me = {
  id: string;
  email: string;
  display_name: string;
  role: 'admin' | 'user';
  must_change_password: boolean;
  locale: string;
  avatar_url: string | null;
  bio: string | null;
  totp_enabled: boolean;
  personalization: boolean;
  explicit_allowed: boolean;
};
export type PlaylistItem = { id: string; position: number; added_at: string; added_by: string | null; added_by_name: string | null; track: Track };
export type PlaylistDetail = PlaylistCard & {
  snapshot_id: number;
  share_token: string;
  invite_token?: string | null;
  owner_avatar: string | null;
  followers: number;
  in_library: boolean;
  is_owner: boolean;
  can_edit: boolean;
  hidden_by_admin: boolean;
  collaborators: { id: string; display_name: string; avatar_url: string | null; role: string }[];
  items: PlaylistItem[];
  created_at: string;
  updated_at: string;
};
export type Genre = { id: number; name: string; kind: 'genre' | 'mood'; color: string; track_count?: number };
